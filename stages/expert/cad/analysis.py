def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter=";"))


def num(value: str, default: float = 0.0) -> float:
    try:
        return float(str(value).replace(",", ".").strip())
    except Exception:
        return default


PARAMS = {row["Параметр"]: row for row in read_csv(FIX3 / "params.csv")}
MASS = {row["Узел"]: row for row in read_csv(FIX3 / "cad" / "mass.csv")}

P = {key: num(row["Значение"]) for key, row in PARAMS.items()}

# геометрия из fix3
L_FRAME = P["L_frame"]
L_VIBRO = P["L_vibro"]
GUIDE_X = (P["guide_x1"], P["guide_x2"])
GUIDE_Y = (P["guide_y1"], P["guide_y2"])
GUIDE_HOLE = P["guide_hole_d"]          # 10.5
SHAFT_D = P["shaft_d"]                  # 10
SHAFT_LEN = P["shaft_guide_len"]        # 166
TABLE_Z0, TABLE_Z1 = P["table_z0"], P["table_z1"]
OVERLAY_Z1 = P["overlay_z1"]
DRIVE_Z = P["drive_z"]
BEARING_X = (P["bearing_x1"], P["bearing_x2"])
CAM_X = (P["cam_x0"], P["cam_x1"])
CAM_AXIS = P["cam_axis_x"]
ROLLER_Z = P["roller_z"]
CAM_STROKES = (3.0, 5.0, 10.0)

# ---------------------------------------------------------------------------
# допущения экспертизы
# ---------------------------------------------------------------------------
G_STEEL = 79300.0          # МПа, модуль сдвига стали
E_STEEL = 200000.0         # МПа
E_PLA = 3500.0             # МПа
NU_PLA = 0.35
E_PETG = 2000.0            # МПа
NU_PETG = 0.40
GRAVITY = 9.80665

# реальные массы покупных узлов (каталог/практика), кг
M_TABLE = num(MASS["table"]["Масса, г"]) / 1000.0
M_OVERLAY = num(MASS["overlay"]["Масса, г"]) / 1000.0
M_LMK_REAL = 0.045         # LMK10UU, 4 шт.
M_BRACKET = num(MASS["bracket"]["Масса, г"]) / 1000.0
M_ROLLER_REAL = 0.015      # 6200
M_AXLE = num(MASS["axle"]["Масса, г"]) / 1000.0
M_ROLL_NUTS = num(MASS["roller_nuts"]["Масса, г"]) / 1000.0
M_TABLE_SCREWS = (num(MASS["table_screws"]["Масса, г"]) +
                  num(MASS["table_nuts"]["Масса, г"])) / 1000.0
M_SPRING_WASHERS_LOWER = 4 * num(MASS["spring_washer"]["Масса, г"]) / 8.0 / 1000.0
M_BALL = 0.033

M_MOVING_REAL = (M_TABLE + M_OVERLAY + 4 * M_LMK_REAL + M_BRACKET +
                 M_ROLLER_REAL + M_AXLE + M_ROLL_NUTS +
                 M_TABLE_SCREWS + M_SPRING_WASHERS_LOWER + M_BALL)
M_LMK_MODEL = num(MASS["lmk"]["Масса, г"]) / 1000.0
M_ROLLER_MODEL = num(MASS["roller"]["Масса, г"]) / 1000.0
M_SHAFT_BEARINGS_MODEL = num(MASS["shaft_bearings"]["Масса, г"]) / 1000.0
M_MOVING_MODEL = (M_TABLE + M_OVERLAY + M_LMK_MODEL + M_BRACKET +
                  M_ROLLER_MODEL + M_AXLE + M_ROLL_NUTS +
                  M_TABLE_SCREWS + M_SPRING_WASHERS_LOWER + M_BALL)
M_TOTAL_MODEL = sum(num(row["Масса, г"]) for row in
                    csv.DictReader((FIX3 / "cad" / "mass.csv").open(encoding="utf-8"),
                                   delimiter=";")
                    if row.get("Узел") not in (None, "", "ИТОГО")) / 1000.0
M_TOTAL_CORR = (M_TOTAL_MODEL - (M_LMK_MODEL - 4 * M_LMK_REAL) -
                (M_ROLLER_MODEL - M_ROLLER_REAL) -
                (M_SHAFT_BEARINGS_MODEL - 2 * 0.015))

# пружина: 12×1,0; средний диаметр 11; 11 активных витков (допущение)
SPRING_D = P["spring_wire"]             # 1.0
SPRING_DM = P["spring_od"] - SPRING_D   # 11.0
SPRING_N = P["spring_turns"]            # 11
SPRING_FREE = P["spring_free"]          # 55
SPRING_INST = P["spring_inst"]          # 36
SPRING_COUNT = 4
SPRING_K = (G_STEEL * SPRING_D ** 4 /
            (8 * SPRING_DM ** 3 * SPRING_N))        # Н/мм
SPRING_K_TOTAL = SPRING_COUNT * SPRING_K
SPRING_PRELOAD = SPRING_K_TOTAL * (SPRING_FREE - SPRING_INST)
M_SPRING_EFF = SPRING_COUNT * 0.0024 / 3.0          # ~1/3 массы пружин
M_DYN = M_MOVING_REAL + M_SPRING_EFF
F_NAT = math.sqrt(SPRING_K_TOTAL * 1000.0 / M_DYN) / (2 * math.pi)

# вал привода
SHAFT_SPAN = BEARING_X[1] - BEARING_X[0]            # 140
SHAFT_MINOR = 8.16                                   # M10, d3
SHAFT_I = math.pi * SHAFT_MINOR ** 4 / 64.0
SHAFT_S = math.pi * SHAFT_MINOR ** 3 / 32.0
CAM_FORCE_DESIGN = 100.0                             # Н, оценка
SHAFT_DEFL = CAM_FORCE_DESIGN * SHAFT_SPAN ** 3 / (48 * E_STEEL * SHAFT_I)
SHAFT_STRESS = CAM_FORCE_DESIGN * SHAFT_SPAN / 4.0 / SHAFT_S

# контакт кулачок — ролик (линейный, Герц)
CAM_R = 50.0
ROLLER_R = P["b6200_od"] / 2.0
CONTACT_R = CAM_R * ROLLER_R / (CAM_R + ROLLER_R)
CONTACT_L = P["b6200_w"]
INV_E = ((1 - NU_PLA ** 2) / E_PLA + (1 - 0.30 ** 2) / E_STEEL)
E_STAR = 1.0 / INV_E
HERTZ_B = math.sqrt(4 * CAM_FORCE_DESIGN * CONTACT_R /
                    (math.pi * CONTACT_L * E_STAR))
HERTZ_P0 = 2 * CAM_FORCE_DESIGN / (math.pi * HERTZ_B * CONTACT_L)

# контакт конусной гайки с PLA-фаской кулачка
NUT_R1, NUT_R2 = 6.0, 5.1
NUT_AREA = math.pi * (NUT_R1 ** 2 - NUT_R2 ** 2)
HUB_P_300 = 300.0 / NUT_AREA
HUB_P_1000 = 1000.0 / NUT_AREA
CAM_TORQUE = CAM_FORCE_DESIGN * (10.0 / 2.0) / 1000.0  # Н·м, max e=5 мм

# наклон вала в отверстии 10,5 при длине отверстия 20 мм
TILT_RAD = math.atan((GUIDE_HOLE - SHAFT_D) / 20.0)
TILT_DEG = math.degrees(TILT_RAD)
TILT_OVER_110 = 110.0 * (GUIDE_HOLE - SHAFT_D) / 20.0

# вторая гармоника эксцентрика с роликом
SECOND_HARM = {s: (s / 2.0) ** 2 / (2 * (45.0 + s / 2.0 + ROLLER_R))
               for s in CAM_STROKES}

# прогиб подстолья (оценка полосы 100×12 мм, пролёт 100 мм, вес дрели 20 Н)
POD_L, POD_B, POD_H = 100.0, 100.0, 12.0
POD_I = POD_B * POD_H ** 3 / 12.0
POD_DEFL = 20.0 * POD_L ** 3 / (48 * E_PETG * POD_I)

# оценка частоты поперечных колебаний рамы (4 стойки, приведённая масса верха)
FRAME_I = 20.0 * 20.0 ** 3 / 12.0
FRAME_K = 4 * 12 * E_PETG * FRAME_I / P["H_frame"] ** 3
FRAME_M = M_DYN + 2.0 + 0.2
FRAME_F = math.sqrt(FRAME_K * 1000.0 / FRAME_M) / (2 * math.pi)

# порог отрыва шарика: a_max = A·ω² > g
def bounce_threshold(stroke_mm: float, mode: str = "peak_to_peak") -> float:
    amplitude_mm = stroke_mm / 2.0 if mode == "peak_to_peak" else stroke_mm
    return math.sqrt(GRAVITY / (amplitude_mm / 1000.0)) / (2 * math.pi)


def contact_force(stroke_mm: float, freq_hz: float, k_total: float = SPRING_K_TOTAL,
                  mass: float = M_DYN, preload: float = SPRING_PRELOAD) -> tuple[float, float, float]:
    """Сила пружины в верхней точке, инерционная сила и сила контакта, Н."""
    amp_mm = stroke_mm / 2.0
    spring_top = preload + k_total * amp_mm
    inertia = mass * (2 * math.pi * freq_hz) ** 2 * amp_mm / 1000.0
    return spring_top, inertia, spring_top - inertia


