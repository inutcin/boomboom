def annotate(src: Path, dst: Path, title: str, calls: list[tuple[int, int, str, str]]) -> None:
    if Image is None or not src.exists():
        return
    im = Image.open(src).convert("RGBA")
    draw = ImageDraw.Draw(im, "RGBA")
    try:
        font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 20)
        small = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 16)
        title_font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 26)
    except Exception:
        font = small = title_font = ImageFont.load_default()
    # title bar
    draw.rectangle((0, 0, im.width, 46), fill=(20, 20, 20, 210))
    draw.text((16, 10), title, fill=(255, 255, 255, 255), font=title_font)
    colors = ["#c0392b", "#b9770e", "#2471a3", "#1e7a3c", "#6c3483"]
    for i, (x, y, fid, text) in enumerate(calls):
        color = colors[i % len(colors)]
        draw.ellipse((x - 16, y - 16, x + 16, y + 16), outline=color, width=4,
                     fill=(255, 255, 255, 70))
        draw.text((x - 12, y - 12), fid.split("/")[0][:2], fill=color, font=small)
        # text box near the callout, clamped
        tw = max(160, len(text) * 10)
        tx = x + 28
        if tx + tw > im.width - 10:
            tx = x - tw - 28
        ty = y - 22
        if ty < 54:
            ty = 54
        if ty + 44 > im.height:
            ty = im.height - 54
        draw.rounded_rectangle((tx, ty, tx + tw, ty + 38), radius=7,
                               fill=(255, 255, 255, 225), outline=color, width=3)
        draw.text((tx + 8, ty + 8), f"{fid}: {text}", fill=(20, 20, 20, 255),
                  font=small)
    im.convert("RGB").save(dst)


