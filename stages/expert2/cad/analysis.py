def bounce_threshold(stroke_mm: float, mode: str = "peak_to_peak") -> float:
    """Порог отрыва шарика: a_max = A·ω² > g."""
    amplitude_mm = stroke_mm / 2.0 if mode == "peak_to_peak" else stroke_mm
    return math.sqrt(GRAVITY / (amplitude_mm / 1000.0)) / (2 * math.pi)


def contact(stroke_mm: float, freq_hz: float,
            k_total: float = SPRING_K_TOTAL, mass: float = M_DYN,
            free: float = SPRING_FREE, top: float = SPRING_INST) -> dict:
    """Силы в верхней и нижней точках хода (вверх — положительное z)."""
    amp = stroke_mm / 2.0 / 1000.0
    omega = 2 * math.pi * freq_hz
    inertia = mass * amp * omega ** 2
    spring_top = k_total * (free - top)
    spring_bot = k_total * (free - (top + stroke_mm))
    return {
        "spring_top": spring_top,
        "spring_bot": spring_bot,
        "inertia": inertia,
        "contact_top": spring_top + mass * GRAVITY - inertia,
        "contact_bot": spring_bot + mass * GRAVITY + inertia,
        "ratio_top": (spring_top + mass * GRAVITY - inertia) / inertia,
        "ratio_bot": (spring_bot + mass * GRAVITY + inertia) / inertia,
    }


def cam_r(theta: float, stroke: float) -> float:
    """Полярный профиль fix5/fix6: r=50−e−e·cos2θ (max при θ=90°)."""
    e = stroke / 2.0
    return CAM_RMAX - e - e * math.cos(2.0 * theta)


@lru_cache(maxsize=None)
def support_function(stroke: float) -> dict:
    """Фактический подъём ролика: h(φ)=max r(θ)·cos(θ−φ).

    Ролик идёт по нормали к профилю, поэтому h(φ) — опорная функция
    профиля, а не полярный радиус r(φ). Для круга они совпадают; для
    двухлепесткового профиля появляются 4-я и 6-я гармоники.
    """
    e = stroke / 2.0
    phi = np.linspace(0.0, 2.0 * math.pi, 1441)
    theta = np.linspace(0.0, 2.0 * math.pi, 3601)
    r = CAM_RMAX - e - e * np.cos(2.0 * theta)
    h = np.max(r[None, :] * np.cos(theta[None, :] - phi[:, None]), axis=1)
    hmax, hmin, mean = float(h.max()), float(h.min()), float(h.mean())
    # гармоники по φ
    amps = {}
    for n in (2, 4, 6, 8):
        a = 2.0 / len(phi) * np.sum((h - mean) * np.cos(n * phi))
        b = 2.0 / len(phi) * np.sum((h - mean) * np.sin(n * phi))
        amps[n] = float(math.hypot(a, b))
    ideal = -e * np.cos(2.0 * phi)
    dev = float(np.max(np.abs((h - mean) - ideal)))
    d2 = np.gradient(np.gradient(h, phi), phi)
    i_top = int(np.argmin(np.abs(phi - math.pi / 2.0)))
    i_bot = int(np.argmin(np.abs(phi)))
    d2_top = float(np.mean(d2[i_top - 2:i_top + 3]))
    # периодическая окрестность нижней точки
    d2_bot = float(np.mean(np.r_[d2[-3:], d2[0:3]]))
    coeff_top = abs(d2_top) / 4.0       # мм, коэффициент при ω_стола²
    coeff_bot = abs(d2_bot) / 4.0
    return {
        "phi": phi, "h": h, "hmax": hmax, "hmin": hmin, "mean": mean,
        "stroke": hmax - hmin, "amps": amps, "dev": dev,
        "d2": d2, "d2_top": d2_top, "d2_bot": d2_bot,
        "coeff_top": coeff_top, "coeff_bot": coeff_bot,
        "thr_actual": math.sqrt(GRAVITY / (coeff_top / 1000.0)) / (2 * math.pi),
    }


def cam_curvature(stroke: float) -> tuple[float, float]:
    """Радиус кривизны профиля в максимуме и минимуме, мм."""
    e = stroke / 2.0
    rmax, rmin = CAM_RMAX, CAM_RMAX - stroke
    rho_max = rmax ** 3 / (rmax ** 2 - rmax * (-4 * e))
    rho_min = rmin ** 3 / (rmin ** 2 - rmin * (4 * e))
    return rho_max, rho_min


def hertz_contact(force: float, rho_cam: float) -> tuple[float, float]:
    """Линейный контакт кулачок (PLA) — ролик 6200 (сталь)."""
    r_equiv = rho_cam * ROLLER_R / (rho_cam + ROLLER_R)
    inv_e = ((1 - NU_PLA ** 2) / E_PLA + (1 - 0.30 ** 2) / E_STEEL)
    e_star = 1.0 / inv_e
    b = math.sqrt(4 * force * r_equiv /
                  (math.pi * P["b6200_w"] * e_star))
    p0 = 2 * force / (math.pi * b * P["b6200_w"])
    return b, p0


